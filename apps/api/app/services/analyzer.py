async def _load_m1(session: AsyncSession, provider: str, symbol: str, now: datetime) -> list[Bar]:
    from app.research.scanner import load_bars

    return await load_bars(session, provider, symbol, now - timedelta(days=LOOKBACK_DAYS), now)


async def _load_d1(session: AsyncSession, provider: str, symbol: str, now: datetime) -> list[Bar]:
    from app.marketdata.store import query_bars

    key = f"apex:analyzer:d1:{provider}:{symbol}:{trading_day(now)}"
    try:
        raw = await get_redis().get(key)
        if raw:
            return [Bar(datetime.fromisoformat(r[0]), *r[1:]) for r in json.loads(raw)]
    except Exception:  # cache is optional  # noqa: S110
        pass
    rows = await query_bars(session, provider=provider, symbol=symbol, timeframe=Timeframe.D1, limit=70)
    bars = [Bar(b.ts, float(b.open), float(b.high), float(b.low), float(b.close), int(b.volume)) for b in rows]
    try:
        await get_redis().set(
            key, json.dumps([[b.ts.isoformat(), b.open, b.high, b.low, b.close, b.volume] for b in bars]), ex=1800
        )
    except Exception:  # cache is optional  # noqa: S110
        pass
    return bars


async def _scan_inputs(
    session: AsyncSession, symbol: str, now: datetime
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    from app.research.scanner import SCAN_KEY

    evaluations: list[dict[str, Any]] = []
    try:
        raw = await get_redis().get(SCAN_KEY)
        doc = json.loads(raw) if raw else {}
        for row in doc.get("symbols", []):
            if row.get("symbol") == symbol:
                evaluations = row.get("evaluations") or []
    except Exception:
        evaluations = []
    rows = (
        await session.scalars(
            select(SignalRow)
            .where(SignalRow.symbol == symbol, SignalRow.created_at >= now - timedelta(hours=2))
            .order_by(SignalRow.created_at.desc())
            .limit(20)
        )
    ).all()
    invalid = {r.strategy_id for r in rows if r.status == "invalidated"}
    for e in evaluations:
        if e["strategy_id"] in invalid and not e.get("triggered"):
            e["invalidated"] = True
    exp = get_settings().signal_expiry_minutes
    sigs = [
        {
            "strategy_id": r.strategy_id,
            "direction": r.direction,
            "entry": r.entry,
            "entry_low": r.entry_low,
            "entry_high": r.entry_high,
            "stop": r.stop,
            "targets": list(r.targets or []),
            "bar_ts": r.bar_ts.isoformat(),
            "created_at": r.created_at.isoformat(),
        }
        for r in rows
        if r.status == "active" and r.created_at >= now - timedelta(minutes=exp)
    ]
    return evaluations, sigs


