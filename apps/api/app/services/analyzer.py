def _narrative(
    bias: str,
    htf: str,
    mid: str,
    short: str,
    pd15: dict[str, Any] | None,
    zone: dict[str, Any] | None,
    sweeps: list[dict[str, Any]],
    shift: dict[str, Any] | None,
    setup: dict[str, Any] | None,
    direction: str | None,
    gates: list[str],
) -> str:
    """Plain-English summary assembled only from detected conditions."""
    parts: list[str] = []
    if bias == "WAIT":
        parts.append("Not enough confirmed structure to form a bias")
    elif bias == "NEUTRAL":
        parts.append(f"Bias is neutral: 1-hour structure is {htf} while 15-minute structure is {mid}")
    else:
        parts.append(f"{bias.capitalize()} bias: 1-hour structure is {htf} and 15-minute structure is {mid}")
    if direction and short in ("bullish", "bearish") and short != direction:
        parts.append(f"The 5-minute chart is in a short-term {short} pullback within that bias")
    if pd15:
        parts.append(f"Price is in the {pd15['zone']} of the 15-minute dealing range")
    if zone:
        kind = "FVG" if zone["type"].endswith("fvg") else "order block"
        parts.append(f"It is revisiting a {zone['status']} {zone['direction']} {kind} on the {zone['timeframe']} chart")
    if sweeps:
        parts.append(f"{sweeps[-1]['side'].capitalize()} liquidity at {sweeps[-1]['label']} was swept and reclaimed")
    if shift:
        parts.append(f"A {shift['timeframe']} {shift['direction']} change of character confirmed afterwards")
    if gates:
        parts.append("Caution: " + gates[0].rstrip("."))
    elif setup:
        parts.append(f"{setup['strategy']} has a {setup['direction']} setup (hypothetical levels, not an order)")
    elif direction:
        parts.append(
            f"Waiting for a confirmed {direction} structure shift before considering a "
            f"{'long' if direction == 'bullish' else 'short'} setup"
        )
    return ". ".join(parts) + "."


