def session_name(now: datetime) -> str:
    t = now.astimezone(ET).time()
    if not is_market_open(now):
        return "Market closed"
    if time(9, 30) <= t < time(11, 30):
        return "New York morning"
    if time(11, 30) <= t < time(13, 30):
        return "New York lunch"
    if time(13, 30) <= t < time(16, 0):
        return "New York afternoon"
    if time(16, 0) <= t < time(17, 0):
        return "Post-close"
    if time(18, 0) <= t or t < time(3, 0):
        return "Asia (overnight)"
    return "London (overnight)"


def _idx_after(bars: Sequence[Bar], ts: datetime) -> int:
    """Index of the last bar that opened before ``ts`` (-1 if none)."""
    lo = -1
    for i, b in enumerate(bars):
        if b.ts < ts:
            lo = i
        else:
            break
    return lo


def period_levels(m1: Sequence[Bar], d1: Sequence[Bar], now: datetime) -> list[dict[str, Any]]:
    """Previous day / week / month high-low from CLOSED daily bars, plus overnight and RTH session levels.

    Daily bars are keyed by trading date (a session starting 18:00 ET belongs to the next date).
    Only periods that have fully ended before the current one are used (no look-ahead).
    """
    out: list[dict[str, Any]] = []
    td = trading_day(now)
    done = [b for b in d1 if b.ts.date() < td]
    if done:
        pd = done[-1]
        out += [
            {
                "name": "Previous day high",
                "short": "PDH",
                "price": pd.high,
                "side": "buy",
                "tf": "1d",
                "formed": pd.ts.date().isoformat(),
                "from": td,
            },
            {
                "name": "Previous day low",
                "short": "PDL",
                "price": pd.low,
                "side": "sell",
                "tf": "1d",
                "formed": pd.ts.date().isoformat(),
                "from": td,
            },
        ]
        wk = td - timedelta(days=td.weekday())
        prev_w = [b for b in done if wk - timedelta(days=7) <= b.ts.date() < wk]
        if prev_w:
            out += [
                {
                    "name": "Previous week high",
                    "short": "PWH",
                    "price": max(b.high for b in prev_w),
                    "side": "buy",
                    "tf": "1w",
                    "formed": prev_w[0].ts.date().isoformat(),
                    "from": wk,
                },
                {
                    "name": "Previous week low",
                    "short": "PWL",
                    "price": min(b.low for b in prev_w),
                    "side": "sell",
                    "tf": "1w",
                    "formed": prev_w[0].ts.date().isoformat(),
                    "from": wk,
                },
            ]
        m0 = td.replace(day=1)
        pm_start = (m0 - timedelta(days=1)).replace(day=1)
        prev_m = [b for b in done if pm_start <= b.ts.date() < m0]
        if prev_m and prev_m[0].ts.date() <= pm_start + timedelta(days=4):  # month mostly covered
            out += [
                {
                    "name": "Previous month high",
                    "short": "PMH",
                    "price": max(b.high for b in prev_m),
                    "side": "buy",
                    "tf": "1M",
                    "formed": pm_start.isoformat(),
                    "from": m0,
                },
                {
                    "name": "Previous month low",
                    "short": "PML",
                    "price": min(b.low for b in prev_m),
                    "side": "sell",
                    "tf": "1M",
                    "formed": pm_start.isoformat(),
                    "from": m0,
                },
            ]
    # Session levels from 1-minute bars.
    today = [b for b in m1 if trading_day(b.ts) == td]
    on = [
        b
        for b in today
        if not is_rth(b.ts) and (b.ts.astimezone(ET).time() < time(9, 30) or b.ts.astimezone(ET).time() >= time(18, 0))
    ]
    rth_today = [b for b in today if is_rth(b.ts)]
    if on:
        final = bool(rth_today)
        out += [
            {
                "name": "Overnight high" + ("" if final else " (developing)"),
                "short": "ONH",
                "price": max(b.high for b in on),
                "side": "buy",
                "tf": "session",
                "formed": td.isoformat(),
                "from": td,
                "after_ts": on[-1].ts,
            },
            {
                "name": "Overnight low" + ("" if final else " (developing)"),
                "short": "ONL",
                "price": min(b.low for b in on),
                "side": "sell",
                "tf": "session",
                "formed": td.isoformat(),
                "from": td,
                "after_ts": on[-1].ts,
            },
        ]
    prior = [b for b in m1 if trading_day(b.ts) < td and is_rth(b.ts)]
    if prior:
        pdate = trading_day(prior[-1].ts)
        sess = [b for b in prior if trading_day(b.ts) == pdate]
        out += [
            {
                "name": "Prior RTH high",
                "short": "pRTH-H",
                "price": max(b.high for b in sess),
                "side": "buy",
                "tf": "session",
                "formed": pdate.isoformat(),
                "from": td,
                "after_ts": sess[-1].ts,
            },
            {
                "name": "Prior RTH low",
                "short": "pRTH-L",
                "price": min(b.low for b in sess),
                "side": "sell",
                "tf": "session",
                "formed": pdate.isoformat(),
                "from": td,
                "after_ts": sess[-1].ts,
            },
        ]
    return out


def _data_status(symbol: str, m1: Sequence[Bar], feed: dict[str, Any], provider: str, now: datetime) -> dict[str, Any]:
    quality = (
        feed.get("quality")
        or ("unavailable" if provider == "none" else "simulated" if provider == "simulated" else "unknown")
    ).lower()
    last = m1[-1] if m1 else None
    age = (now - (last.ts + Timeframe.M1.delta)).total_seconds() if last else None
    open_ = is_market_open(now)
    stale = bool(last) and open_ and age is not None and age > 180
    if provider == "none" or not last:
        label = "UNAVAILABLE"
    elif quality == "simulated":
        label = "SIMULATED"
    elif stale:
        label = "STALE"
    elif not open_:
        label = "MARKET CLOSED"
    else:
        label = quality.upper()
    contract = (feed.get("contracts") or {}).get(symbol)
    return {
        "label": label,
        "available": bool(last),
        "provider": provider,
        "quality": quality,
        "price": last.close if last else None,
        "price_time": (last.ts + Timeframe.M1.delta).isoformat() if last else None,
        "age_seconds": round(age) if age is not None else None,
        "stale": stale,
        "market_open": open_,
        "contract": contract,
        "feed_state": feed.get("state"),
        "note": None
        if last
        else f"DATA UNAVAILABLE: {_cause(symbol, provider, feed)}. Prices are never derived from another instrument.",
    }


def _vwap(m5: Sequence[Bar]) -> dict[str, Any]:
    vw, sd = session_vwap(m5)
    if not m5 or not vw or vw[-1] is None:
        return {"available": False}
    px = m5[-1].close
    dev = (px - vw[-1]) / sd[-1] if sd and sd[-1] else None
    return {
        "available": True,
        "vwap": round(vw[-1], 4),
        "side": "above" if px > vw[-1] else "below",
        "deviation_sd": round(dev, 2) if dev is not None else None,
    }


def _volatility(m5: Sequence[Bar]) -> dict[str, Any]:
    if len(m5) < 60:
        return {"state": "unknown", "detail": "Not enough 5-minute bars."}
    a = causal_atr(m5, 14)
    short, long_ = a[-1], sum(a[-60:]) / 60
    ratio = short / long_ if long_ else None
    vols = [b.volume for b in m5[-21:-1]]
    rvol = m5[-1].volume / (sum(vols) / len(vols)) if vols and sum(vols) else None
    st = "unknown" if ratio is None else "compressed" if ratio < 0.7 else "expanded" if ratio > 1.5 else "normal"
    return {
        "state": st,
        "atr_ratio": round(ratio, 2) if ratio else None,
        "relative_volume": round(rvol, 2) if rvol else None,
        "atr_5m": round(short, 4),
    }


def _active_zone(zones: Sequence[dict[str, Any]], price: float, direction: str, tol: float) -> dict[str, Any] | None:
    """A still-valid zone of ``direction`` that price is currently inside or within ``tol`` of."""
    for z in zones:
        if z["direction"] != direction or z["status"] in ("invalidated", "fully mitigated"):
            continue
        if z["bottom"] - tol <= price <= z["top"] + tol:
            return z
    return None


def strategy_status(evaluations: Sequence[dict[str, Any]], bias_dir: str) -> dict[str, list[dict[str, Any]]]:
    """Confirmed / Developing / Conflicting / Invalidated / Not applicable per strategy, by family."""
    by_id = {e["strategy_id"]: e for e in evaluations}
    out: dict[str, list[dict[str, Any]]] = {}
    for fam, ids in FAMILIES.items():
        rows = []
        for sid in ids:
            e = by_id.get(sid)
            if e is None:
                rows.append(
                    {
                        "id": sid,
                        "name": STRATEGY_NAMES[sid],
                        "status": "Not applicable",
                        "detail": "No scanner evaluation available.",
                    }
                )
                continue
            side = e.get("side")
            ratio = e["passed"] / e["total"] if e.get("total") else 0.0
            note = (e.get("note") or "").lower()
            if e.get("invalidated"):
                status, detail = "Invalidated", "A recent signal from this strategy was invalidated."
            elif e.get("triggered"):
                agree = bias_dir in ("neutral", "wait") or (side == "long") == (bias_dir == "bullish")
                status = "Confirmed" if agree else "Conflicting"
                detail = f"{side} signal; all conditions met." + ("" if agree else " Opposes the broader bias.")
            elif not e.get("total") or "insufficient" in note or "not eligible" in note or "outside" in note:
                status, detail = "Not applicable", e.get("note") or "Conditions not evaluable now."
            elif ratio >= 0.6:
                status, detail = "Developing", f"{e['passed']}/{e['total']} conditions met."
            else:
                status, detail = "Not applicable", f"Only {e['passed']}/{e['total']} conditions met."
            missing = [c["name"] for c in e.get("conditions", []) if not c.get("passed")][:3]
            rows.append(
                {
                    "id": sid,
                    "name": STRATEGY_NAMES[sid],
                    "status": status,
                    "detail": detail,
                    "side": side,
                    "missing": missing,
                }
            )
        out[fam] = rows
    return out


