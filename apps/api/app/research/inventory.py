"""Strategy inventory generated from the registered strategies themselves (never hand-maintained)."""

from __future__ import annotations

import inspect
from pathlib import Path
from typing import Any

from app.research.backtest import EVAL_END, EVAL_START, FLAT_BY
from app.services.checklist import ChecklistConfig, reward_risk
from app.strategies.base import MIN_BARS_5M, Strategy
from app.strategies.library import STRATEGIES

EXAMPLE_STOPS = {"ES": (5.0, 10.0), "NQ": (20.0, 40.0)}  # points; illustrative stop sizes for the net R:R example


def _net_examples(t1_r: float) -> dict[str, list[dict[str, float]]]:
    out: dict[str, list[dict[str, float]]] = {}
    for sym, stops in EXAMPLE_STOPS.items():
        rows = []
        for pts in stops:
            r = reward_risk(sym, "long", 10000.0, 10000.0 - pts, 10000.0 + t1_r * pts, ChecklistConfig())
            rows.append({"stop_points": pts, "gross_rr": r["gross_ratio"], "net_rr": r["ratio"]})
        out[sym] = rows
    return out


def inventory() -> list[dict[str, Any]]:
    root = Path(__file__).resolve().parents[2]
    items = []
    for s in STRATEGIES:
        sp = s.spec
        cls = type(s)
        try:
            src = Path(inspect.getsourcefile(cls) or "").resolve().relative_to(root)
            line = inspect.getsourcelines(cls)[1]
            where = f"apps/api/{src}:{line}"
        except (TypeError, OSError, ValueError):
            where = cls.__module__
        explicit_targets = "targets = (" in inspect.getsource(cls)  # builds targets from liquidity levels
        complete = cls._side is not Strategy._side and all(
            getattr(sp, f) for f in ("entry", "invalidation", "stop", "targets", "regime")
        )
        items.append(
            {
                "id": sp.id,
                "code": sp.code,
                "name": sp.name,
                "purpose": sp.regime,
                "source": where,
                "timeframes": sp.timeframe,
                "required_data": sp.required_data,
                "instruments": list(sp.eligible_instruments),
                "es_nq_eligible": {k: k in sp.eligible_instruments for k in ("ES", "NQ")},
                "directions": "long and short (both sides are evaluated on every bar; the side whose conditions all "
                "pass signals)",
                "signal_window_et": f"{s.window[0]:%H:%M}-{s.window[1]:%H:%M}",
                "backtest_window_et": f"signals {EVAL_START:%H:%M}-{EVAL_END:%H:%M}, flat by {FLAT_BY:%H:%M}",
                "warm_up": f">= {MIN_BARS_5M} completed 5-minute bars, ATR(14) and EMA(50) available",
                "entry": sp.entry,
                "invalidation": sp.invalidation,
                "stop": sp.stop,
                "targets": sp.targets,
                "target_r_design": list(s.target_r),
                "targets_from_structure": explicit_targets,
                "time_exit": sp.time_exit,
                "costs": sp.costs,
                "net_rr_examples_t1": _net_examples(s.target_r[0]),
                "implementation_complete": complete,
                "eligible_for_evaluation": complete and all(k in sp.eligible_instruments for k in ("ES", "NQ")),
                "notes": "SMC strategies are slower to evaluate (pattern detection per bar)."
                if sp.id.startswith("smc_")
                else "",
            }
        )
    return items


def inventory_md(items: list[dict[str, Any]]) -> str:
    lines = [
        "# Strategy inventory (generated from the registered strategies)",
        "",
        "Generated by `python -m app.cli strategy-inventory`. Net R:R examples use the app's cost model "
        "($2.50/side commission, 1 tick slippage on entry and stop, none on a limit target) at illustrative "
        "stop sizes; they show why a T1 placed at 1.0R or 1.5R before costs can never reach 1.5 net.",
        "",
    ]
    for it in items:
        ex = "; ".join(
            f"{sym}: " + ", ".join(f"{r['stop_points']:g}pt stop -> net {r['net_rr']}" for r in rows)
            for sym, rows in it["net_rr_examples_t1"].items()
        )
        lines += [
            f"## {it['name']} (`{it['id']}`)",
            "",
            f"- Source: `{it['source']}`; timeframes {it['timeframes']}; ES/NQ eligible: {it['es_nq_eligible']}",
            f"- Purpose / regime: {it['purpose']}",
            f"- Directions: {it['directions']}; signal window {it['signal_window_et']} ET; {it['backtest_window_et']}",
            f"- Entry: {it['entry']}",
            f"- Stop: {it['stop']}",
            f"- Targets: {it['targets']} (design R multiples {it['target_r_design']}"
            + (", structure-based targets where available" if it["targets_from_structure"] else "")
            + ")",
            f"- Invalidation: {it['invalidation']}",
            f"- Time exit: {it['time_exit']}",
            f"- Net R:R to T1 examples: {ex}",
            f"- Warm-up: {it['warm_up']}",
            f"- Implementation complete: {it['implementation_complete']}; eligible for evaluation: "
            f"{it['eligible_for_evaluation']}" + (f". {it['notes']}" if it["notes"] else ""),
            "",
        ]
    return "\n".join(lines)
